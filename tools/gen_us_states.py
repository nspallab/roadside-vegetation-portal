"""Build data/us_states.js: SVG paths of the lower 48 states for the member-agency map on the Team page.

Input: gis_source_data/Census_States/US_States_TIGERweb_generalized.geojson (Census TIGERweb States, generalized).
Projection: USGS Albers equal-area conic for the conterminous U.S. (standard parallels 29.5 and 45.5 N, centre 96 W).

Usage (from the repository root):
  python tools/gen_us_states.py gis_source_data data
Writes us_states.js (window.US_STATES = {w, h, states: [{abbr, name, d}], uiuc: [x, y]}).
"""
import json, math, sys

GIS, OUT = sys.argv[1], sys.argv[2]
W, H, PAD = 960, 600, 10
LAT1, LAT2, LAT0, LON0 = map(math.radians, (29.5, 45.5, 23.0, -96.0))
n = (math.sin(LAT1) + math.sin(LAT2)) / 2
C = math.cos(LAT1) ** 2 + 2 * n * math.sin(LAT1)
rho0 = math.sqrt(C - 2 * n * math.sin(LAT0)) / n


def albers(lon, lat):
    lon, lat = math.radians(lon), math.radians(lat)
    rho = math.sqrt(C - 2 * n * math.sin(lat)) / n
    th = n * (lon - LON0)
    return rho * math.sin(th), rho0 - rho * math.cos(th)


def simplify(pts, eps):  # Douglas-Peucker on projected points
    if len(pts) < 4:
        return pts
    keep, stack = {0, len(pts) - 1}, [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        L = math.hypot(x2 - x1, y2 - y1) or 1e-9
        best, bi = 0, None
        for i in range(a + 1, b):
            d = abs((x2 - x1) * (y1 - pts[i][1]) - (x1 - pts[i][0]) * (y2 - y1)) / L
            if d > best:
                best, bi = d, i
        if bi is not None and best > eps:
            keep.add(bi)
            stack += [(a, bi), (bi, b)]
    return [pts[i] for i in sorted(keep)]


def simplify_ring(pts, eps):  # a closed ring starts and ends on the same point: split it at the farthest point first
    if pts[0] == pts[-1]:
        pts = pts[:-1]
    if len(pts) < 4:
        return pts
    m = max(range(len(pts)), key=lambda i: math.dist(pts[0], pts[i]))
    return simplify(pts[:m + 1], eps)[:-1] + simplify(pts[m:] + [pts[0]], eps)[:-1]


def ring_area(pts):
    return abs(sum(pts[i][0] * pts[i - 1][1] - pts[i - 1][0] * pts[i][1] for i in range(len(pts)))) / 2


feats = [f for f in json.load(open(f"{GIS}/Census_States/US_States_TIGERweb_generalized.geojson"))["features"]
         if f["properties"]["STUSAB"] not in ("AK", "HI")]
rings = []  # (feature index, projected ring)
for fi, f in enumerate(feats):
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        for ring in poly:
            rings.append((fi, [albers(lon, lat) for lon, lat in ring]))
xs = [p[0] for _, r in rings for p in r]; ys = [p[1] for _, r in rings for p in r]
X0, X1, Y0, Y1 = min(xs), max(xs), min(ys), max(ys)
k = min((W - 2 * PAD) / (X1 - X0), (H - 2 * PAD) / (Y1 - Y0))
W, H = round((X1 - X0) * k + 2 * PAD), round((Y1 - Y0) * k + 2 * PAD)
to_px = lambda p: ((p[0] - X0) * k + PAD, (Y1 - p[1]) * k + PAD)

paths = {fi: [] for fi in range(len(feats))}
for fi, r in rings:
    px = simplify_ring([to_px(p) for p in r], 0.45)
    if len(px) < 4 or ring_area(px) < 6:  # drop specks (small islands) that would not show at this size
        continue
    paths[fi].append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in px) + "Z")

states = [{"abbr": f["properties"]["STUSAB"], "name": f["properties"]["NAME"], "d": "".join(paths[fi])}
          for fi, f in enumerate(feats) if paths[fi]]
states.sort(key=lambda s: s["name"])
uiuc = [round(v, 1) for v in to_px(albers(-88.2272, 40.1020))]  # Urbana, Illinois
out = {"w": W, "h": H, "states": states, "uiuc": uiuc}
open(f"{OUT}/us_states.js", "w", encoding="utf-8", newline="\n").write(
    "/* Generated by tools/gen_us_states.py. Census TIGERweb States (generalized), USGS Albers, lower 48 + DC. */\n"
    "window.US_STATES = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(states), "states,", W, "x", H, "px")
